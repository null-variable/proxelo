//go:build ignore

// schemagen writes schema.json: a JSON Schema (draft 2020-12 subset) of
// every resource spec, read from this package's source so field comments
// become descriptions and typed string constants become enums. The web
// console renders its forms from it.
//
// Run with go generate ./internal/model.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"log"
	"os"
	"reflect"
	"sort"
	"strconv"
	"strings"
)

type schema struct {
	Type        string             `json:"type,omitempty"`
	Ref         string             `json:"$ref,omitempty"`
	Description string             `json:"description,omitempty"`
	Format      string             `json:"format,omitempty"`
	Enum        []string           `json:"enum,omitempty"`
	Minimum     *int               `json:"minimum,omitempty"`
	Properties  map[string]*schema `json:"properties,omitempty"`
	Order       []string           `json:"x-order,omitempty"`
	Required    []string           `json:"required,omitempty"`
	Items       *schema            `json:"items,omitempty"`
	Additional  *schema            `json:"additionalProperties,omitempty"`
	// Pointer fields: unset is different from the zero value.
	Nullable bool `json:"x-nullable,omitempty"`
	// Resource kind (plural) an ID field refers to.
	RefKind string `json:"x-ref,omitempty"`
	// Set by the control plane; forms show it but never send it.
	ReadOnly bool `json:"readOnly,omitempty"`
}

type doc struct {
	Schema  string             `json:"$schema"`
	Defs    map[string]*schema `json:"$defs"`
	Kinds   map[string]string  `json:"x-kinds"`
	Comment string             `json:"$comment"`
}

func main() {
	fset := token.NewFileSet()
	pkgs, err := parser.ParseDir(fset, ".", func(fi os.FileInfo) bool {
		return !strings.HasSuffix(fi.Name(), "_test.go") && fi.Name() != "schemagen.go"
	}, parser.ParseComments)
	if err != nil {
		log.Fatal(err)
	}
	g := gen{structs: map[string]*ast.StructType{}, docs: map[string]string{}, strs: map[string]bool{}, enums: map[string][]string{}}
	for _, f := range pkgs["model"].Files {
		g.collect(f)
	}
	kinds := map[string]string{
		"listeners": "ListenerSpec", "sites": "SiteSpec", "routes": "RouteSpec",
		"upstreams": "UpstreamSpec", "certificates": "CertificateSpec", "policies": "PolicySpec",
		"lookups": "LookupSpec",
	}
	out := doc{
		Schema:  "https://json-schema.org/draft/2020-12/schema",
		Defs:    map[string]*schema{},
		Kinds:   kinds,
		Comment: "Generated by internal/model/schemagen.go; do not edit.",
	}
	var names []string
	for _, n := range kinds {
		names = append(names, n)
	}
	sort.Strings(names)
	for len(names) > 0 {
		n := names[0]
		names = names[1:]
		if _, done := out.Defs[n]; done {
			continue
		}
		s, deps := g.structSchema(n)
		out.Defs[n] = s
		names = append(names, deps...)
	}
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetIndent("", "  ")
	enc.SetEscapeHTML(false)
	if err := enc.Encode(out); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("schema.json", b.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
}

type gen struct {
	structs map[string]*ast.StructType
	docs    map[string]string
	// Named string types.
	strs  map[string]bool
	enums map[string][]string
}

func (g *gen) collect(f *ast.File) {
	for _, d := range f.Decls {
		gd, ok := d.(*ast.GenDecl)
		if !ok {
			continue
		}
		switch gd.Tok {
		case token.TYPE:
			for _, sp := range gd.Specs {
				ts := sp.(*ast.TypeSpec)
				c := ts.Doc
				if c == nil && len(gd.Specs) == 1 {
					c = gd.Doc
				}
				g.docs[ts.Name.Name] = text(c)
				switch t := ts.Type.(type) {
				case *ast.StructType:
					g.structs[ts.Name.Name] = t
				case *ast.Ident:
					if t.Name == "string" {
						g.strs[ts.Name.Name] = true
					}
				}
			}
		case token.CONST:
			for _, sp := range gd.Specs {
				vs := sp.(*ast.ValueSpec)
				id, ok := vs.Type.(*ast.Ident)
				if !ok || len(vs.Values) != 1 {
					continue
				}
				lit, ok := vs.Values[0].(*ast.BasicLit)
				if !ok || lit.Kind != token.STRING {
					continue
				}
				v, _ := strconv.Unquote(lit.Value)
				g.enums[id.Name] = append(g.enums[id.Name], v)
			}
		}
	}
}

func text(c *ast.CommentGroup) string {
	if c == nil {
		return ""
	}
	return strings.Join(strings.Fields(c.Text()), " ")
}

func (g *gen) structSchema(name string) (*schema, []string) {
	st, ok := g.structs[name]
	if !ok {
		log.Fatalf("no struct %s", name)
	}
	s := &schema{Type: "object", Description: g.docs[name], Properties: map[string]*schema{}}
	var deps []string
	for _, f := range st.Fields.List {
		if len(f.Names) == 0 {
			// Embedded: inline its fields.
			id, ok := f.Type.(*ast.Ident)
			if !ok {
				log.Fatalf("%s: embedded %T", name, f.Type)
			}
			in, d := g.structSchema(id.Name)
			for _, k := range in.Order {
				s.Properties[k] = in.Properties[k]
				s.Order = append(s.Order, k)
			}
			s.Required = append(s.Required, in.Required...)
			deps = append(deps, d...)
			continue
		}
		tag := ""
		if f.Tag != nil {
			v, _ := strconv.Unquote(f.Tag.Value)
			tag = reflect.StructTag(v).Get("json")
		}
		jn, opts, _ := strings.Cut(tag, ",")
		if jn == "-" || !f.Names[0].IsExported() {
			continue
		}
		if jn == "" {
			jn = f.Names[0].Name
		}
		p, d := g.typeSchema(f.Type)
		deps = append(deps, d...)
		if desc := text(f.Doc); desc != "" {
			p.Description = desc
		}
		if refKind := idRef(f.Names[0].Name, p.Description); refKind != "" {
			if p.Type == "array" {
				p.Items.RefKind = refKind
			} else {
				p.RefKind = refKind
			}
		}
		p.ReadOnly = strings.HasPrefix(p.Description, "Set by the control plane")
		s.Properties[jn] = p
		s.Order = append(s.Order, jn)
		if !strings.Contains(opts, "omitempty") && !strings.Contains(opts, "omitzero") && !p.Nullable {
			s.Required = append(s.Required, jn)
		}
	}
	return s, deps
}

// idRef recognizes fields that hold resource IDs from their comments, as
// the model documents them: "Listener IDs.", "Site ID served ...".
func idRef(field, desc string) string {
	for _, k := range []struct{ word, kind string }{
		{"Listener", "listeners"}, {"Site", "sites"}, {"Route", "routes"},
		{"Upstream", "upstreams"}, {"Certificate", "certificates"}, {"Policy", "policies"},
	} {
		if strings.HasPrefix(desc, k.word+" ID") {
			return k.kind
		}
	}
	switch field {
	case "Children", "Routes":
		if strings.Contains(desc, "Route IDs") || field == "Children" {
			return "routes"
		}
	case "Policies":
		return "policies"
	case "Upstream":
		return "upstreams"
	}
	return ""
}

func (g *gen) typeSchema(e ast.Expr) (*schema, []string) {
	switch t := e.(type) {
	case *ast.StarExpr:
		s, d := g.typeSchema(t.X)
		s.Nullable = true
		return s, d
	case *ast.ArrayType:
		s, d := g.typeSchema(t.Elt)
		return &schema{Type: "array", Items: s}, d
	case *ast.MapType:
		s, d := g.typeSchema(t.Value)
		return &schema{Type: "object", Additional: s}, d
	case *ast.SelectorExpr:
		if fmt.Sprint(t.X) == "time" && t.Sel.Name == "Time" {
			return &schema{Type: "string", Format: "date-time"}, nil
		}
	case *ast.Ident:
		switch t.Name {
		case "string":
			return &schema{Type: "string"}, nil
		case "bool":
			return &schema{Type: "boolean"}, nil
		case "int", "int32", "int64":
			return &schema{Type: "integer"}, nil
		case "uint", "uint8", "uint16", "uint32", "uint64":
			zero := 0
			return &schema{Type: "integer", Minimum: &zero}, nil
		}
		if g.strs[t.Name] {
			return &schema{Type: "string", Enum: g.enums[t.Name], Description: g.docs[t.Name]}, nil
		}
		if _, ok := g.structs[t.Name]; ok {
			return &schema{Ref: "#/$defs/" + t.Name}, []string{t.Name}
		}
	}
	log.Fatalf("unsupported type %s", fmt.Sprint(e))
	return nil, nil
}
